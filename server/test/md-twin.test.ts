/**
 * The .txt twins must match the .md they mirror.
 *
 * Every prose doc in this repo carries a plain-text twin, because markdown
 * renders in only some of the places these files get read: GitHub shows raw
 * markup in diffs and review, and editors and pagers show it always.
 *
 * The twins used to be written by hand, and by the time this test arrived
 * they had already drifted from each other - em dashes turned to hyphens in
 * one file and not the next, list text re-wrapped in one twin and not its
 * source. None of it was caught, because the failure mode of a hand-kept
 * duplicate is that nobody reads both copies. The one person reading the
 * .txt has no way to know it disagrees with the .md.
 *
 * So the twins are generated by scripts/md-txt.mjs and this test runs its
 * --check: edit a .md, forget to regenerate, and the suite fails here rather
 * than shipping a mirror that quietly says something else.
 *
 * Line endings are normalised on both sides. The working tree is CRLF on
 * Windows (core.autocrlf) and LF in the repository and on CI, so a literal
 * comparison would pass or fail depending on which machine ran it - the
 * worst kind of check, since it would be green exactly where it was written.
 */
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { render, sources, stale, twinOf } from "../scripts/md-txt.mjs";

const REPO = join(fileURLToPath(new URL(".", import.meta.url)), "..", "..");

describe("the plain-text twins are generated, and in sync", () => {
  it("every twin matches its source", () => {
    // The message names the stale files, so a failure says what to fix.
    expect(stale()).toEqual([]);
  });

  it("finds the prose docs, and not prepack's copies of them", () => {
    const found = sources().map((s) => s.slice(REPO.length + 1).replace(/\\/g, "/"));
    expect(found).toContain("README.md");
    expect(found).toContain("PLAN.md");
    expect(found).toContain("SECURITY.md");
    expect(found).toContain("skill/SKILL.md");
    // prepack drops gitignored copies at server/README.md and server/skill/;
    // twinning a build artifact would only write files the next pack replaces.
    expect(found.some((f) => f.startsWith("server/"))).toBe(false);
  });

  it("keeps frontmatter byte for byte", () => {
    // The description is parsed by whatever loads the skill. Stripping a
    // backtick out of it would change the value a client reads, which is the
    // one transformation a plain-text mirror must never make.
    const out = render(["---", "name: x", "description: a `b` and **c**", "---", "", "# H", "text"].join("\n"));
    expect(out.split("\n").slice(0, 4)).toEqual(["---", "name: x", "description: a `b` and **c**", "---"]);
  });

  it("underlines headings, strips inline markup, and keeps link targets", () => {
    const out = render(["# Title", "", "## Section", "", "**bold** and `code` and [text](https://e.example)."].join("\n"));
    expect(out).toContain("Title\n=====");
    expect(out).toContain("Section\n-------");
    expect(out).toContain("bold and code and text (https://e.example).");
  });

  it("does not print a link target that is already the link text", () => {
    // The README links build-version.json to itself. Rendering that as
    // "build-version.json (build-version.json)" says nothing twice.
    expect(render("See [build-version.json](build-version.json).")).toContain("See build-version.json.");
    expect(render("See [the file](build-version.json).")).toContain("See the file (build-version.json).");
    // The README writes that self-link with inline-code markers, which come
    // off after the link is expanded - so the comparison has to ignore them.
    expect(render("See [`build-version.json`](build-version.json).")).toContain("See build-version.json.");
    // SECURITY.md links the address to itself through mailto:, which is the
    // same thing said twice once the scheme is taken off.
    expect(render("email [dev@evomedia.net](mailto:dev@evomedia.net), not a list").trim()).toBe(
      "email dev@evomedia.net, not a list",
    );
    // A different target is information, so both halves are kept.
    expect(render("[the policy](https://example.net/p)").trim()).toBe("the policy (https://example.net/p)");
  });

  // What is inside backticks is content, not markup: running the emphasis and
  // HTML rules over it corrupts the thing being documented. Each of these had
  // already been rendered wrong somewhere in the fleet - a glob written as
  // `Civil Parties*JWEB*.txt` came out as "Civil PartiesJWEB.txt", two words
  // glued into one.
  it("treats inline code as content, not markup", () => {
    expect(render("`Civil Parties*JWEB*.txt` is a file")).toContain("Parties*JWEB*.txt");
    expect(render("A section containing `<ol>` only")).toContain("<ol>");
    expect(render("Selectors look like `role=button[name=\"Save\"]`")).toContain('role=button[name="Save"]');
    expect(render("The manifest names `steps[i].title`")).toContain("steps[i].title");
    expect(render("Run `a~~b~~c` now")).toContain("a~~b~~c");
  });

  // They read as punctuation, and `~` is also what underlines a third-level
  // heading - so a struck-out phrase looks like markup in the one file whose
  // job is to have none.
  it("strips strikethrough markers", () => {
    expect(render("~~old~~ -> new").trim()).toBe("old -> new");
  });

  // Matched against real element names, never `</?\w+>`: these docs write
  // placeholders the same way, and a generic pattern deletes those words.
  it("leaves only the words of a raw HTML block", () => {
    const out = render('<picture><source srcset="a.png"><img src="b.png" alt="evomedia.net"></picture>');
    expect(out.trim()).toBe("evomedia.net");
    expect(render("git clone https://host/<owner>/<repo>.git")).toContain("<owner>/<repo>");
    expect(render("documentation at docs.<site> or /help")).toContain("docs.<site>");
  });

  it("drops fence markers and indents the code inside", () => {
    const out = render(["Run it:", "", "```bash", "npm test", "```"].join("\n"));
    expect(out).toContain("    npm test");
    expect(out).not.toContain("```");
  });

  it("the skill twin still carries the description the client reads", async () => {
    // SKILL.md is both machine-loaded and prose, so it is twinned - and the
    // description is the part a client reads to decide the skill applies.
    const txt = await readFile(join(REPO, "skill", "SKILL.txt"), "utf8");
    const md = await readFile(join(REPO, "skill", "SKILL.md"), "utf8");
    const line = (s: string) => s.split(/\r?\n/).find((l) => l.startsWith("description:"));
    expect(line(txt)).toBe(line(md));
  });
});
